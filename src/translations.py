def localize_text(text: str) -> str:
    """Resolve explicit panel labels using the addon language, including English and Portuguese.

    Blender's native translation can be disabled independently; the addon's
    own language preference should still work for these labels.
    """
    if not text:
        return text
    from .localized_errors import decode_message, render_message
    decoded = decode_message(text)
    if isinstance(decoded, dict):
        return render_message(decoded)
    loc = get_addon_locale()
    if loc == 'en_US':
        return TRANSLATIONS_DICT.get('en_US', {}).get(('*', text), text)
    elif loc == 'pt_BR':
        return TRANSLATIONS_DICT.get('pt_BR', {}).get(('*', text), text)
    return text


def report_msg(pt_text: str, en_text: str) -> str:
    """Retorna pt_text ou en_text dependendo do idioma ativo do add-on/Blender."""
    return en_text if get_addon_locale() == 'en_US' else pt_text


